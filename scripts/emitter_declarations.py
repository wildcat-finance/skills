class GitReader:
    """Read blobs from a local clone with a fixed git argv and no shell."""

    def __init__(self, clone: str):
        self.clone = os.path.abspath(clone)

    def _git(self, arguments: list[str]) -> bytes:
        argv = ["git", "-C", self.clone, "--no-pager", *arguments]
        env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
        env.update(GIT_NO_REPLACE_OBJECTS="1", GIT_TERMINAL_PROMPT="0", GIT_OPTIONAL_LOCKS="0")
        try:
            result = subprocess.run(  # phylax: allow subprocess: fixed git argv list, validated ref and path, no shell
                argv, capture_output=True, timeout=GIT_TIMEOUT_SECONDS, check=False, env=env,
            )
        except (OSError, subprocess.TimeoutExpired) as err:
            raise read_failure(f"git {arguments[0]} did not complete: {type(err).__name__}") from None
        if result.returncode != 0:
            raise read_failure(f"git {' '.join(arguments[-1:])} exited {result.returncode}")
        return result.stdout

    def read(self, ref: str, path: str) -> bytes:
        ref, path = _safe_ref(ref), _safe_path(path)
        data = self._git(["show", "--no-textconv", "--end-of-options", f"{ref}:{path}"])
        if len(data) > MAX_FILE_BYTES:
            raise read_failure(f"{path} at {ref} is {len(data)} bytes, over the {MAX_FILE_BYTES}-byte cap")
        return data

    def list_sources(self, ref: str) -> dict[str, str]:
        """Return {path: blob id} for every `.sol` file under src/ at ref."""
        ref = _safe_ref(ref)
        listing = self._git(["ls-tree", "-r", "-z", "--full-tree", "--end-of-options", ref, SOURCE_PREFIX.rstrip("/")])
        found = {}
        for record in listing.decode("utf-8", "strict").split("\x00"):
            if not record:
                continue
            meta, _, path = record.partition("\t")
            fields = meta.split()
            if len(fields) == 3 and fields[1] == "blob" and path.endswith(".sol"):
                found[_safe_path(path)] = fields[2]
        return found


class _HostPinnedRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        target = urllib.parse.urlsplit(newurl)
        if target.scheme != "https" or target.hostname != ALLOWED_HOST:
            raise read_failure(f"redirect to {target.scheme}://{target.hostname} refused")
        return super().redirect_request(req, fp, code, msg, headers, newurl)


class HttpsReader:
    """Read blobs from raw.githubusercontent.com at a pinned commit."""

    list_sources = None

    def __init__(self, opener=None):
        self.opener = opener or urllib.request.build_opener(_HostPinnedRedirect)

    @staticmethod
    def url(ref: str, path: str) -> str:
        ref, path = _safe_ref(ref), _safe_path(path)
        return f"https://{ALLOWED_HOST}/{REPOSITORY}/{ref}/{urllib.parse.quote(path)}"

    def read(self, ref: str, path: str) -> bytes:
        url = self.url(ref, path)
        if urllib.parse.urlsplit(url).hostname != ALLOWED_HOST:
            raise read_failure(f"host for {path} is not {ALLOWED_HOST}")
        try:
            with self.opener.open(url, timeout=HTTPS_TIMEOUT_SECONDS) as response:  # phylax: allow url: fixed host, pinned commit, digest-verified
                final = urllib.parse.urlsplit(response.geturl())
                if final.scheme != "https" or final.hostname != ALLOWED_HOST:
                    raise read_failure(f"{path} was served from {final.hostname}")
                data = response.read(MAX_FILE_BYTES + 1)
        except Refusal:
            raise
        except (OSError, ValueError) as err:
            raise read_failure(f"{path} at {ref} could not be fetched: {type(err).__name__}") from None
        if len(data) > MAX_FILE_BYTES:
            raise read_failure(f"{path} at {ref} exceeds the {MAX_FILE_BYTES}-byte cap")
        return data


