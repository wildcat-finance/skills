def scan(sources: dict[str, str], deployments: dict[str, dict], emitter_files=EMITTER_FILES) -> dict:
    """Build the table body from decoded sources and parsed build files.

    deployments maps a contract name to {"input": standard JSON input,
    "output": compiler output}.
    """
    resolver = TypeResolver(sources)
    unreviewed, emitters = [], []
    for path in emitter_files:
        found, stray = parse_emitters(path, sources.get(path, ""))
        emitters += found
        unreviewed += stray
    declarations = []
    for path in sorted(sources):
        found, failed = parse_declarations(path, sources[path], resolver)
        declarations += found
        unreviewed += failed
    views = {c: abi_events(d["output"]) for c, d in sorted(deployments.items())}
    callers = {}
    for contract, d in sorted(deployments.items()):
        carried = d["input"].get("sources", {})
        callers[contract] = (set(carried), {p: mask(s.get("content", "")) for p, s in carried.items()
                                            if isinstance(s, dict) and isinstance(s.get("content"), str)})
    for e in emitters:
        for p in e.get("params", []):
            p["canonical"] = resolver.resolve(p["type"])
    rows, emitted = [], set()
    for e in emitters:
        name = e["emitter"][len("emit_"):]
        at = f"{e['path']}:{e['line']}"
        if "unreviewed" in e:
            unreviewed.append({"kind": "emitter", "name": e["emitter"], "at": at, "reason": e["unreviewed"]})
            continue
        matches = [d for d in declarations if d["name"] == name]
        if not matches:
            unreviewed.append({"kind": "emitter", "name": e["emitter"], "at": at,
                               "reason": "no same-named event declaration under src/"})
            continue
        call = re.compile(r"\b" + re.escape(e["emitter"]) + r"\s*\(")
        reached = sorted(c for c, (paths, masked) in callers.items() if e["path"] in paths and any(
            call.search(text) for p, text in masked.items() if p != e["path"]))
        for d in matches:
            emitted.add(d["qualified"] + "@" + d["at"])
            rows.append(_row(e, d, name, at, views, reached, unreviewed))
    without = []
    for d in declarations:
        if d["qualified"] + "@" + d["at"] not in emitted:
            without.append({"declaration": d["qualified"], "declared_at": d["at"],
                            "signature": signature(d["name"], d["inputs"])})
    mismatches = [{"emitter": r["emitter"], "declaration": r["declaration"], "declared_at": r["declared_at"],
                   "classes": r["classes"]} for r in rows if r["classes"]]
    return {
        "rows": rows,
        "mismatches": mismatches,
        "unreviewed": sorted(unreviewed, key=lambda u: (u["at"], u["kind"], u["name"])),
        "declarations_without_emitter": sorted(without, key=lambda w: (w["declared_at"], w["declaration"])),
        "summary": {
            "emitters": len(emitters),
            "rows": len(rows),
            "compared_rows": sum(r["status"] != "unreviewed" for r in rows),
            "abi_checked_rows": sum(bool(r["abi_checked"]) for r in rows),
            "mismatch_rows": len(mismatches),
            "unreviewed": len(unreviewed),
            "declarations_without_emitter": len(without),
        },
    }


def _row(e, d, name, at, views, reached, unreviewed) -> dict:
    sig = signature(name, d["inputs"])
    row = {
        "emitter": e["emitter"], "emitter_at": at, "log_at": f"{e['path']}:{e['log_line']}",
        "declaration": d["qualified"], "declared_at": d["at"],
        "signature": sig, "topic0": topic0_of(sig), "topic0_literal": e["topic0_literal"],
        "anonymous": d["anonymous"], "log_arity": e["arity"],
        "indexed_positions": [n for n, i in enumerate(d["inputs"]) if i["indexed"]],
        "topic_args": e["topic_args"], "data_bytes": e["data_bytes"], "data_args": e["data_args"],
        "abi_checked": [], "reached_by": reached, "classes": [], "notes": [],
    }
    if not reached:
        row["notes"].append("called from no bound deployed build")
    if d["unresolved"]:
        row["status"] = "unreviewed"
        reason = "parameter type " + ", ".join(f"`{t}`" for t in d["unresolved"]) + " has no resolved canonical ABI type"
        row["notes"].append(reason)
        unreviewed.append({"kind": "row", "name": f"{e['emitter']} / {d['qualified']}", "at": d["at"], "reason": reason})
        return row
    if not all(one_word(i["type"]) for i in d["inputs"]):
        row["status"] = "unreviewed"
        reason = "a parameter is not a one-word static type; layout not compared"
        row["notes"].append(reason)
        unreviewed.append({"kind": "row", "name": f"{e['emitter']} / {d['qualified']}", "at": d["at"], "reason": reason})
        return row
    classes = compare(e, d["inputs"], d["anonymous"], name)
    for contract, events in views.items():
        candidates = events.get(name, [])
        if len(candidates) > 1:
            row["notes"].append(f"{contract} ABI has {len(candidates)} events named {name}; not compared")
        elif candidates:
            view = candidates[0]
            if any(i["type"] is None for i in view["inputs"]):
                row["notes"].append(f"{contract} ABI entry for {name} has an unreadable type; not compared")
                continue
            row["abi_checked"].append(contract)
            classes += [f"abi:{contract}:{c}" for c in compare(e, view["inputs"], view["anonymous"], name)]
    row["classes"] = sorted(set(classes))
    row["status"] = "mismatch" if row["classes"] else "compared"
    if len(e["params"]) == len(d["inputs"]):
        pairs = list(zip(e["params"], d["inputs"]))
        for p, i in pairs:
            if p["canonical"] != i["type"]:
                row["notes"].append(f"emitter parameter `{p['name']}` is `{p['type']}` where the declaration says "
                                    f"`{i['type']}`; recorded, not graded")
        narrow = [f"`{p['name']}` (`{p['type']}`)" for p, i in pairs
                  if not i["indexed"] and sub_word(p["canonical"])]
        if narrow:
            row["notes"].append("sub-word values " + ", ".join(narrow) + " are written by mstore as full words; "
                                "their cleaning is not graded")
    return row


def _entry(path: str, ref: str, role: str, data: bytes) -> dict:
    return {"path": path, "ref": ref, "role": role, "blob": git_blob_id(data),
            "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}


def _decode(path: str, data: bytes) -> str:
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        raise read_failure(f"{path} is not UTF-8") from None


def _json(path: str, data: bytes) -> dict:
    try:
        value = json.loads(_decode(path, data))
    except json.JSONDecodeError:
        raise read_failure(f"{path} is not JSON") from None
    if not isinstance(value, dict):
        raise read_failure(f"{path} is not a JSON object")
    return value


def assemble(files: list[tuple[dict, bytes]], commit: str, compiler_ref: str) -> dict:
    """Build the whole table from (source-block entry, bytes) pairs."""
    total = sum(len(data) for _entry_, data in files)
    if total > MAX_TOTAL_BYTES:
        raise read_failure(f"{total} bytes read, over the {MAX_TOTAL_BYTES}-byte total cap")
    sources = {e["path"]: _decode(e["path"], data) for e, data in files if e["role"] == "source"}
    by_path = {e["path"]: data for e, data in files}
    deployments, block = {}, []
    for contract, address in DEPLOYMENTS:
        input_path, output_path = deployment_paths(contract, address)
        if input_path not in by_path or output_path not in by_path:
            raise read_failure(f"{contract} build files were not read")
        deployments[contract] = {"input": _json(input_path, by_path[input_path]),
                                 "output": _json(output_path, by_path[output_path])}
        block.append({"contract": contract, "address": address,
                      "standard_input": input_path,
                      "standard_input_sha256": hashlib.sha256(by_path[input_path]).hexdigest(),
                      "output": output_path,
                      "output_sha256": hashlib.sha256(by_path[output_path]).hexdigest()})
    entries = []
    for e, data in sorted(files, key=lambda f: f[0]["path"]):
        entry = dict(e)
        if entry["role"] == "source":
            text = sources[entry["path"]]
            binding = {}
            for contract, d in sorted(deployments.items()):
                carried = d["input"].get("sources", {}).get(entry["path"])
                binding[contract] = "absent" if carried is None else (
                    "equal" if isinstance(carried, dict) and carried.get("content") == text else "differs")
            entry["in_builds"] = binding
        entries.append(entry)
    body = scan(sources, deployments)
    body["summary"]["binding_differs"] = sorted(
        e["path"] for e in entries if "differs" in e.get("in_builds", {}).values())
    body["schema"] = SCHEMA
    body["source"] = {
        "repository": REPOSITORY, "commit": commit, "compiler_output_ref": compiler_ref,
        "declaration_scope": "every .sol file under src/ at commit",
        "emitter_files": list(EMITTER_FILES), "deployments": block, "files": entries,
    }
    return body


def serialize(table: dict) -> bytes:
    return (json.dumps(table, indent=2, sort_keys=True, ensure_ascii=True) + "\n").encode("utf-8")


def read_build(reader, ref: str, compiler_ref: str) -> list[tuple[dict, bytes]]:
    """Read every file a git build needs, checking each blob against the tree."""
    listed = reader.list_sources(ref)
    files = []
    for path in sorted(listed):
        data = reader.read(ref, path)
        if git_blob_id(data) != listed[path]:
            raise read_failure(f"{path} at {ref}: bytes do not hash to listed blob {listed[path]}")
        files.append((_entry(path, ref, "source", data), data))
    for contract, address in DEPLOYMENTS:
        for role, path in zip(("standard-input", "compiler-output"), deployment_paths(contract, address)):
            data = reader.read(compiler_ref, path)
            files.append((_entry(path, compiler_ref, role, data), data))
    return files


def load_table(path: str) -> tuple[bytes, dict]:
    try:
        with open(path, "rb") as fh:
            raw = fh.read(MAX_TOTAL_BYTES + 1)
    except OSError as err:
        raise Refusal("table-invalid", f"{path} cannot be read: {type(err).__name__}") from None
    try:
        table = json.loads(raw.decode("utf-8"))
        source = table["source"]
        files = source["files"]
        ok = (table.get("schema") == SCHEMA and isinstance(files, list) and all(
            isinstance(f, dict) and {"path", "ref", "role", "blob", "bytes", "sha256"} <= set(f) for f in files))
        _safe_ref(source["commit"])
        _safe_ref(source["compiler_output_ref"])
        for f in files:
            _safe_path(f["path"])
            _safe_ref(f["ref"])
    except (UnicodeDecodeError, json.JSONDecodeError, KeyError, TypeError, Refusal):
        ok = False
    if not ok:
        raise Refusal("table-invalid", f"{path} is not a {SCHEMA} table")
    return raw, table


def read_table_sources(reader, table: dict, source_ref: str | None) -> tuple[list[tuple[dict, bytes]], list[str]]:
    """Read the table's files, with src/ at source_ref; return (files, drift lines)."""
    drift, files = [], []
    table_sources = {f["path"] for f in table["source"]["files"] if f["role"] == "source"}
    read_ref = source_ref or table["source"]["commit"]
    listed = None
    if reader.list_sources is not None:
        listed = set(reader.list_sources(read_ref))
        for path in sorted(listed - table_sources):
            drift.append(f"{path} is present at {read_ref} and absent from the table")
        for path in sorted(table_sources - listed):
            drift.append(f"{path} is in the table and absent at {read_ref}")
    for f in table["source"]["files"]:
        ref = read_ref if f["role"] == "source" else f["ref"]
        if f["role"] == "source" and listed is not None and f["path"] not in listed:
            continue
        data = reader.read(ref, f["path"])
        seen = _entry(f["path"], ref, f["role"], data)
        if (seen["bytes"], seen["sha256"], seen["blob"]) != (f["bytes"], f["sha256"], f["blob"]):
            drift.append(f"{f['path']} at {ref}: sha256 {f['sha256']} -> {seen['sha256']}, "
                         f"bytes {f['bytes']} -> {seen['bytes']}")
        files.append(({**seen, "ref": f["ref"]}, data))
    return files, drift


def render_markdown(table: dict) -> str:
    """Render the reader's table from the JSON table, deterministically."""
    def cell(value) -> str:
        text = value if isinstance(value, str) else json.dumps(value, sort_keys=True)
        return text.replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")

    source, summary = table["source"], table["summary"]
    compiler_label = (f"`{source['compiler_output_ref']}` (tag `{COMPILER_OUTPUT_TAG}`)"
                      if source["compiler_output_ref"] == COMPILER_OUTPUT_REF
                      else f"`{source['compiler_output_ref']}`")
    lines = [
        "# Emitter declarations", "",
        f"Schema `{table['schema']}`. Source `{source['repository']}` at commit "
        f"`{source['commit']}`; compiler output at {compiler_label}.", "",
        "Mismatch classes: " + ", ".join(f"`{c}`" for c in MISMATCH_CLASSES)
        + "; a class found against a build's ABI is prefixed `abi:<contract>:`.", "",
        "## Regenerating this table", "",
        "```sh", "python3 scripts/emitter_declarations.py build --from-git <clone> "
        "--out docs/kickoff/1361/emitters.json --markdown docs/kickoff/1361/emitters.md",
        "```", "",
        "Verify without writing:", "",
        "```sh", "python3 scripts/emitter_declarations.py check --from-git <clone> "
        "--table docs/kickoff/1361/emitters.json", "```", "",
        "## Scope and limits", "",
        RUNTIME_DIFFERENTIAL_NOTE, "",
        SPHEREXCONFIG_CORRECTION_NOTE, "",
        "## Builds", "",
        "| Contract | Address | Standard input SHA-256 | Output SHA-256 |",
        "| --- | --- | --- | --- |",
    ]
    for d in source["deployments"]:
        lines.append(f"| {d['contract']} | `{d['address']}` | `{d['standard_input_sha256']}` | `{d['output_sha256']}` |")
    lines += ["", "## Summary", "", "| Count | Value |", "| --- | --- |"]
    for key in sorted(summary):
        lines.append(f"| {cell(key)} | {cell(summary[key])} |")
    lines += ["", "## Rows", "",
              "| Emitter | Declaration | Signature | topic0 | logN | Indexed | Data bytes | ABI checked | Reached by | Status | Classes | Notes |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in table["rows"]:
        lines.append("| " + " | ".join([
            f"`{r['emitter']}` ({cell(r['emitter_at'])})", f"`{r['declaration']}` ({cell(r['declared_at'])})",
            f"`{cell(r['signature'])}`", f"`{cell(r['topic0'])}`", cell(r["log_arity"]),
            cell(r["indexed_positions"]), cell(r["data_bytes"]), cell(", ".join(r["abi_checked"]) or "none"),
            cell(", ".join(r["reached_by"]) or "none"), cell(r["status"]),
            cell(", ".join(r["classes"]) or "none"), cell("; ".join(r["notes"]) or "none"),
        ]) + " |")
    for title, key, columns in (
        ("Mismatches", "mismatches", ("emitter", "declaration", "declared_at", "classes")),
        ("Unreviewed", "unreviewed", ("kind", "name", "at", "reason")),
        ("Declarations with no assembly emitter", "declarations_without_emitter",
         ("declaration", "declared_at", "signature")),
    ):
        lines += ["", f"## {title}", ""]
        if not table[key]:
            lines.append("None.")
            continue
        lines.append("| " + " | ".join(columns) + " |")
        lines.append("| " + " | ".join("---" for _ in columns) + " |")
        for item in table[key]:
            lines.append("| " + " | ".join(cell(", ".join(item[c]) if isinstance(item[c], list) else item[c])
                                           for c in columns) + " |")
    unreached = [r for r in table["rows"] if not r["reached_by"] and r["status"] == "compared"]
    lines += ["", "## Not reached by any deployed build", "",
              "A row here compared cleanly against its declaration but its emitter is never called "
              "from a source file bound into a listed build; the source-level dead-code and unused-slot "
              "cases named in the study belong here.", ""]
    if not unreached:
        lines.append("None.")
    else:
        lines.append("| Emitter | Declaration | Declared at |")
        lines.append("| --- | --- | --- |")
        for r in unreached:
            lines.append(f"| `{r['emitter']}` ({cell(r['emitter_at'])}) | `{r['declaration']}` | {cell(r['declared_at'])} |")
    lines += ["", "## Source files", "", "| Path | Ref | Blob | Bytes | SHA-256 | In builds |",
              "| --- | --- | --- | --- | --- | --- |"]
    for f in source["files"]:
        builds = ", ".join(f"{k}={v}" for k, v in sorted(f.get("in_builds", {}).items())) or f["role"]
        lines.append(f"| `{f['path']}` | `{f['ref']}` | `{f['blob']}` | {f['bytes']} | `{f['sha256']}` | {cell(builds)} |")
    lines.append("")
    return "\n".join(lines)


def atomic_write(path: str, data: bytes) -> None:
    """Write data to path through a sibling temporary file and os.replace."""
    directory = os.path.dirname(os.path.abspath(path))
    handle, temporary = tempfile.mkstemp(prefix=".emitter-declarations-", dir=directory)
    try:
        with os.fdopen(handle, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def _diff_lines(expected: bytes, actual: bytes, label: str) -> list[str]:
    diff = difflib.unified_diff(expected.decode("utf-8", "replace").splitlines(),
                                actual.decode("utf-8", "replace").splitlines(),
                                f"{label} (committed)", f"{label} (regenerated)", n=0, lineterm="")
    return [line for _i, line in zip(range(12), diff)]


def run_build(reader, out: str, markdown: str | None, ref: str, compiler_ref: str, table_path: str | None) -> dict:
    if reader.list_sources is None:
        if table_path is None:
            raise Refusal("read-failure", "an HTTPS build needs --table for its path list and digests")
        _raw, committed = load_table(table_path)
        if (ref, compiler_ref) != (committed["source"]["commit"], committed["source"]["compiler_output_ref"]):
            raise Refusal("source-drift", "an HTTPS build reads only the table's refs")
        files, drift = read_table_sources(reader, committed, None)
        if drift:
            raise Refusal("source-drift", "; ".join(drift))
    else:
        files = read_build(reader, ref, compiler_ref)
    table = assemble(files, ref, compiler_ref)
    atomic_write(out, serialize(table))
    if markdown:
        atomic_write(markdown, render_markdown(table).encode("utf-8"))
    return table


def run_check(reader, table_path: str, markdown: str | None, source_ref: str | None) -> list[str]:
    """Return refusal lines; empty when the committed table regenerates exactly."""
    raw, committed = load_table(table_path)
    files, drift = read_table_sources(reader, committed, source_ref)
    if drift:
        return [f"source-drift: {line}" for line in drift] + [
            f"source-drift: {len(drift)} source differences from {table_path}; the table was not regenerated"]
    table = assemble(files, committed["source"]["commit"], committed["source"]["compiler_output_ref"])
    regenerated = serialize(table)
    problems = []
    if regenerated != raw:
        problems.append(f"table-difference: {table_path} differs from the table regenerated from matching source")
        problems += [f"table-difference: {line}" for line in _diff_lines(raw, regenerated, table_path)]
    if markdown:
        try:
            with open(markdown, "rb") as fh:
                committed_md = fh.read(MAX_TOTAL_BYTES + 1)
        except OSError as err:
            return problems + [f"markdown-difference: {markdown} cannot be read: {type(err).__name__}"]
        rendered = render_markdown(table).encode("utf-8")
        if rendered != committed_md:
            problems.append(f"markdown-difference: {markdown} differs from its rendering of the table")
            problems += [f"markdown-difference: {line}" for line in _diff_lines(committed_md, rendered, markdown)]
    return problems


def _commit(value: str) -> str:
    if not _COMMIT.match(value):
        raise argparse.ArgumentTypeError(f"{value!r} is not a 40-hex commit")
    return value


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    subparsers = parser.add_subparsers(dest="command", required=True)
    build = subparsers.add_parser("build", help="regenerate the emitter table")
    check = subparsers.add_parser("check", help="compare a regenerated table with the committed one")
    for sub in (build, check):
        origin = sub.add_mutually_exclusive_group(required=True)
        origin.add_argument("--from-git", metavar="CLONE", help="read from a local v2-protocol clone")
        origin.add_argument("--from-https", action="store_true", help=f"read from {ALLOWED_HOST}")
        sub.add_argument("--markdown", metavar="PATH", help="the rendered Markdown table")
    build.add_argument("--out", required=True, metavar="PATH", help="where to write the JSON table")
    build.add_argument("--ref", type=_commit, default=PIN, help="source commit (default the pin)")
    build.add_argument("--abi-ref", type=_commit, default=COMPILER_OUTPUT_REF, help="compiler-output commit")
    build.add_argument("--table", metavar="PATH", help="existing table naming the paths an HTTPS build reads")
    check.add_argument("--table", required=True, metavar="PATH", help="the committed JSON table")
    check.add_argument("--ref", type=_commit, help="read src/ at this commit instead of the table's")
    return parser


def main(argv: list[str] | None = None, reader=None) -> int:
    args = build_parser().parse_args(argv)
    if reader is None:
        reader = HttpsReader() if args.from_https else GitReader(args.from_git)
    try:
        if args.command == "build":
            table = run_build(reader, args.out, args.markdown, args.ref, args.abi_ref, args.table)
            s = table["summary"]
            print(f"build: {s['emitters']} emitters, {s['rows']} rows, {s['mismatch_rows']} mismatch rows, "
                  f"{s['unreviewed']} unreviewed; wrote {args.out}", file=sys.stderr)
            return 0
        problems = run_check(reader, args.table, args.markdown, args.ref)
    except Refusal as refusal:
        print(str(refusal), file=sys.stderr)
        return 1
    for line in problems:
        print(line, file=sys.stderr)
    if problems:
        return 1
    print(f"check: {args.table} regenerates exactly", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
