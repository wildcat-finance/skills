#!/usr/bin/env python3
"""Check a target's assembly event emitters against their declarations.

    python3 scripts/emitter_declarations.py build --from-git CLONE --out TABLE.json [--markdown TABLE.md]
    python3 scripts/emitter_declarations.py check --from-git CLONE --table TABLE.json [--ref COMMIT]
    python3 scripts/emitter_declarations.py check --from-https --table TABLE.json

`build` reads `wildcat-finance/v2-protocol` at `--ref` (default the pin) and
the compiler output at `--abi-ref` (default tag v2.0.0), scans every
`emit_<Name>` function in the two emitter files, pairs each with every
same-named `event` declared in any `.sol` file under `src/`, and compares it
with the declaration text and with the compiler ABI of the WildcatMarket and
HooksFactory builds. Its source block names every file it read: each `.sol`
file under `src/` at the ref, and the standard input and output of both
builds at the compiler-output ref. A found mismatch is written as a row with
its classes; it never fails `build`. Over HTTPS, `build` reads exactly the
paths of an existing `--table` at that table's refs, because a raw host cannot
list a tree, and refuses any byte that differs from it.

`check` takes the refs and paths from the committed table's source block.
`--ref` changes only the commit the `src/` bytes are read at; the table stays
the oracle. Before scanning, every read file must match the table's size, git
blob id and SHA-256, and with `--from-git` the `.sol` file list under `src/`
must match the table's. `check` writes nothing.

Exit status: 0 when the table is written (`build`) or matches (`check`); 1 on
any refusal; 2 on a usage error. Each refusal line on stderr starts with one
prefix: `source-drift:` when read bytes or the file list differ from the
table, `table-difference:` or `markdown-difference:` when the source matches
but the regenerated bytes differ, `read-failure:` when a file cannot be read
or exceeds its cap, and `table-invalid:` when the committed table is not a
readable v1 table.

The scan is static text analysis. It runs no target code and makes no claim
about runtime behaviour, bytecode identity or capture completeness.
"""

