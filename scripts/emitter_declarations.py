def mask(text: str) -> str:
    """Blank comments and string contents, keeping every offset and newline."""
    out = list(text)
    i, n = 0, len(text)
    while i < n:
        ch = text[i]
        if ch == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                out[i] = " "
                i += 1
        elif ch == "/" and i + 1 < n and text[i + 1] == "*":
            end = text.find("*/", i + 2)
            end = n if end < 0 else end + 2
            for k in range(i, end):
                if text[k] != "\n":
                    out[k] = " "
            i = end
        elif ch in "\"'":
            i += 1
            while i < n and text[i] != ch and text[i] != "\n":
                out[i] = " "
                if text[i] == "\\" and i + 1 < n:
                    out[i + 1] = " " if text[i + 1] != "\n" else "\n"
                    i += 1
                i += 1
            i += 1
        else:
            i += 1
    return "".join(out)


def _close(text: str, start: int, opening: str, closing: str) -> int | None:
    """Index of the bracket that closes text[start], or None when unbalanced."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == opening:
            depth += 1
        elif text[i] == closing:
            depth -= 1
            if depth == 0:
                return i
    return None


def split_args(text: str) -> list[str]:
    parts, depth, current = [], 0, []
    for ch in text:
        if ch == "," and depth == 0:
            parts.append("".join(current).strip())
            current = []
            continue
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        current.append(ch)
    tail = "".join(current).strip()
    if tail or parts:
        parts.append(tail)
    return parts


def _line(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def parse_param(text: str, event: bool) -> dict | None:
    """Split one parameter into its type text, indexed flag and name."""
    text = re.sub(r"\s*\[\s*", "[", text)
    text = re.sub(r"\s*\]", "]", text)
    words = text.split()
    if not words or not _TYPE.match(words[0]):
        return None
    kind, rest = words[0], words[1:]
    if kind == "address" and rest[:1] == ["payable"]:
        rest = rest[1:]
    indexed = False
    if event and rest[:1] == ["indexed"]:
        indexed, rest = True, rest[1:]
    if not event and rest[:1] and rest[0] in _LOCATIONS:
        rest = rest[1:]
    if len(rest) > 1 or (rest and not _IDENT.match(rest[0])):
        return None
    return {"type_text": kind, "indexed": indexed, "name": rest[0] if rest else ""}


def _spans(clean: str) -> list[tuple[int, int, str, str]]:
    """(start, end, kind, name) for each contract, interface and library body."""
    spans = []
    for m in re.finditer(r"\b(contract|interface|library)\s+([A-Za-z_]\w*)[^{;]*\{", clean):
        end = _close(clean, m.end() - 1, "{", "}")
        spans.append((m.start(), len(clean) if end is None else end, m.group(1), m.group(2)))
    return spans


def _owner(spans, offset: int) -> str | None:
    inside = [s for s in spans if s[0] <= offset <= s[1]]
    return max(inside, key=lambda s: s[0])[3] if inside else None


class TypeResolver:
    """Map Solidity parameter types to canonical ABI types.

    A contract or interface is `address`, an enum is `uint8`, a user-defined
    value type is its underlying type, a struct is the tuple of its members,
    and array suffixes are kept. A name with no definition, or with
    definitions that disagree, resolves to None and its row is unreviewed.
    """

    def __init__(self, sources: dict[str, str]):
        self.defs: dict[str, list[tuple[str | None, str, object]]] = {}
        for path in sorted(sources):
            clean = mask(sources[path])
            spans = _spans(clean)
            for start, _end, kind, name in spans:
                self._add(name, _owner([s for s in spans if s[0] < start], start), kind, None)
            for m in re.finditer(r"\benum\s+([A-Za-z_]\w*)\s*\{", clean):
                self._add(m.group(1), _owner(spans, m.start()), "enum", None)
            for m in re.finditer(r"\btype\s+([A-Za-z_]\w*)\s+is\s+([A-Za-z_]\w*)\s*;", clean):
                self._add(m.group(1), _owner(spans, m.start()), "udvt", m.group(2))
            for m in re.finditer(r"\bstruct\s+([A-Za-z_]\w*)\s*\{", clean):
                end = _close(clean, m.end() - 1, "{", "}")
                members = None
                if end is not None:
                    members = []
                    for item in clean[m.end():end].split(";"):
                        if item.strip():
                            parsed = parse_param(item, event=False)
                            members.append(parsed["type_text"] if parsed else None)
                self._add(m.group(1), _owner(spans, m.start()), "struct", members)

    def _add(self, name, owner, kind, detail):
        self.defs.setdefault(name, []).append((owner, kind, detail))

    def resolve(self, type_text: str, _stack: frozenset = frozenset()) -> str | None:
        match = _TYPE.match(type_text or "")
        if not match:
            return None
        base, suffix = match.group(1), match.group(2)
        canonical = self._base(base, _stack)
        return None if canonical is None else canonical + suffix

    def _base(self, base: str, stack: frozenset) -> str | None:
        if base in ("uint", "int"):
            return base + "256"
        if base in ("address", "bool", "string", "bytes"):
            return base
        sized = _SIZED.match(base)
        if sized:
            width = int(sized.group(2))
            if sized.group(1) == "bytes":
                return base if 1 <= width <= 32 else None
            return base if 8 <= width <= 256 and width % 8 == 0 else None
        if base in stack:
            return None
        *qualifier, name = base.split(".")
        found = set()
        for owner, kind, detail in self.defs.get(name, []):
            if qualifier and owner != qualifier[-1]:
                continue
            if kind in ("contract", "interface"):
                found.add("address")
            elif kind == "enum":
                found.add("uint8")
            elif kind == "udvt":
                found.add(self.resolve(detail, stack | {base}))
            elif kind == "struct":
                parts = [self.resolve(t, stack | {base}) if t else None for t in (detail or [None])]
                found.add(None if None in parts or detail is None else "(" + ",".join(parts) + ")")
            else:
                found.add(None)
        return found.pop() if len(found) == 1 else None


def one_word(canonical: str | None) -> bool:
    """True for a static value type that occupies exactly one ABI word."""
    if canonical is None or "[" in canonical or "(" in canonical:
        return False
    return canonical not in ("string", "bytes")


def sub_word(canonical: str | None) -> bool:
    if canonical in ("address", "bool"):
        return True
    sized = _SIZED.match(canonical or "")
    if not sized:
        return False
    width = int(sized.group(2))
    return width < 32 if sized.group(1) == "bytes" else width < 256


def _literal(token: str, constants: dict[str, int]) -> int | None:
    token = token.strip()
    if token in constants:
        return constants[token]
    return int(token, 0) if _NUMBER.match(token) else None


def parse_emitters(path: str, text: str) -> tuple[list[dict], list[dict]]:
    """Return (emitters, stray log sites) for one emitter file."""
    clean = mask(text)
    constants = {}
    for m in re.finditer(r"\buint[0-9]*\s+constant\s+([A-Za-z_]\w*)\s*=\s*(0x[0-9a-fA-F]+|[0-9]+)\s*;", clean):
        constants[m.group(1)] = int(m.group(2), 0)
    emitters, bodies = [], []
    for m in re.finditer(r"\bfunction\s+(emit_[A-Za-z_]\w*)\s*\(", clean):
        row = {"emitter": m.group(1), "path": path, "line": _line(clean, m.start())}
        emitters.append(row)
        reason = _parse_emitter(clean, m.end() - 1, constants, row, bodies)
        if reason:
            row["unreviewed"] = reason
    stray = []
    for m in re.finditer(r"\blog[0-4]\s*\(", clean):
        if not any(start <= m.start() < end for start, end in bodies):
            stray.append({"kind": "log-site", "name": m.group(0).rstrip("( "), "at": f"{path}:{_line(clean, m.start())}",
                          "reason": "log site outside any emit_ function body"})
    return emitters, stray


def _parse_emitter(clean, open_paren, constants, row, bodies) -> str | None:
    close = _close(clean, open_paren, "(", ")")
    if close is None:
        return "unbalanced parameter list"
    brace, semicolon = clean.find("{", close + 1), clean.find(";", close + 1)
    if brace < 0 or 0 <= semicolon < brace or not _WORDS.fullmatch(clean, close + 1, brace):
        return "no function body"
    body_start = brace + 1
    body_end = _close(clean, body_start - 1, "{", "}")
    if body_end is None:
        return "unbalanced function body"
    bodies.append((body_start, body_end))
    params = []
    for item in split_args(clean[open_paren + 1:close]):
        parsed = parse_param(item, event=False)
        if parsed is None or not parsed["name"]:
            return f"parameter {item.strip()!r} does not parse"
        params.append(parsed)
    row["params"] = [{"name": p["name"], "type": p["type_text"]} for p in params]
    body = clean[body_start:body_end]
    logs = list(re.finditer(r"\blog([0-4])\s*\(", body))
    row["log_sites"] = len(logs)
    if len(logs) != 1:
        return f"{len(logs)} log sites in the body"
    other = _OTHER_MEMORY_WRITES.search(body)
    if other:
        return f"body writes memory with {other.group(1)}"
    log = logs[0]
    arity = int(log.group(1))
    end = _close(body, log.end() - 1, "(", ")")
    if end is None:
        return "unbalanced log arguments"
    args = split_args(body[log.end():end])
    if len(args) != 2 + arity:
        return f"log{arity} has {len(args)} arguments"
    row["arity"] = arity
    row["log_line"] = _line(clean, body_start + log.start())
    size = _literal(args[1], constants)
    if size is None:
        return f"data size {args[1]!r} is not a literal"
    row["data_bytes"] = size
    row["topic0_literal"] = None
    if arity:
        topic = args[2]
        if _TOPIC_LITERAL.match(topic):
            row["topic0_literal"] = topic.lower()
        elif topic in constants:
            row["topic0_literal"] = "0x%064x" % constants[topic]
        else:
            return f"topic0 {topic!r} is not a literal"
    for topic in args[3:]:
        if not _IDENT.match(topic):
            return f"topic {topic!r} is an expression"
    row["topic_args"] = args[3:]
    base = args[0]
    base_literal = _literal(base, constants)
    words = {}
    for store in re.finditer(r"\bmstore\s*\(", body[:log.start()]):
        close_store = _close(body, store.end() - 1, "(", ")")
        pair = split_args(body[store.end():close_store]) if close_store is not None else []
        if len(pair) != 2:
            return "mstore does not parse"
        target, value = pair
        offset = None
        added = split_args(target[4:-1]) if target.startswith("add(") and target.endswith(")") else []
        if target == base:
            offset = 0
        elif len(added) == 2 and base in added:
            offset = _literal(added[1] if added[0] == base else added[0], constants)
        elif base_literal is not None and _literal(target, constants) is not None:
            offset = _literal(target, constants) - base_literal
        if offset is None:
            return f"mstore target {target!r} is not relative to the data base"
        if offset < 0 or offset >= size:
            continue
        if offset % 32:
            return f"mstore at data offset {offset} is not word-aligned"
        if not _IDENT.match(value):
            return f"data word at offset {offset} is an expression"
        words[offset] = value
    row["data_args"] = [words.get(32 * w) for w in range(size // 32)]
    return None


def parse_declarations(path: str, text: str, resolver: TypeResolver) -> tuple[list[dict], list[dict]]:
    clean = mask(text)
    spans = _spans(clean)
    decls, failed = [], []
    for m in re.finditer(r"\bevent\s+([A-Za-z_]\w*)\s*\(", clean):
        name, at = m.group(1), f"{path}:{_line(clean, m.start())}"
        owner = _owner(spans, m.start())
        qualified = f"{owner or '<file>'}.{name}"
        close = _close(clean, m.end() - 1, "(", ")")
        tail = re.compile(r"\s*(anonymous\s*)?;").match(clean, close + 1) if close is not None else None
        if tail is None:
            failed.append({"kind": "declaration", "name": qualified, "at": at, "reason": "declaration does not parse"})
            continue
        inputs, unresolved = [], []
        for item in split_args(clean[m.end():close]):
            parsed = parse_param(item, event=True)
            if parsed is None:
                unresolved.append(item.strip())
                inputs.append({"type": None, "type_text": item.strip(), "indexed": False, "name": ""})
                continue
            canonical = resolver.resolve(parsed["type_text"])
            if canonical is None:
                unresolved.append(parsed["type_text"])
            inputs.append({"type": canonical, "type_text": parsed["type_text"],
                           "indexed": parsed["indexed"], "name": parsed["name"]})
        decls.append({"name": name, "qualified": qualified, "at": at, "path": path,
                      "inputs": inputs, "anonymous": bool(tail.group(1)), "unresolved": unresolved})
    return decls, failed


def signature(name: str, inputs: list[dict]) -> str | None:
    if any(i["type"] is None for i in inputs):
        return None
    return f"{name}({','.join(i['type'] for i in inputs)})"


def topic0_of(sig: str | None) -> str | None:
    return None if sig is None else "0x" + keccak256(sig.encode("utf-8")).hex()


def compare(emitter: dict, inputs: list[dict], anonymous: bool, name: str) -> list[str]:
    """Mismatch classes between one emitter and one declaration view.

    Expected values come from the declaration's types, indexed flags and
    anonymity; the emitter's literal is only ever the value under test.

    A genuinely anonymous `logN` call reserves no topic0 slot: every topic
    word is an indexed value. The scan still reads `args[2]` provisionally
    as `topic0_literal` (S2-R1-01, since anonymity is not known until a
    declaration is paired here), so under this anonymous view that word is
    folded back into the indexed sequence rather than dropped from it.
    """
    classes = []
    indexed = [n for n, i in enumerate(inputs) if i["indexed"]]
    data = [n for n, i in enumerate(inputs) if not i["indexed"]]
    if anonymous:
        classes.append("anonymous-declared")
    if emitter["arity"] != len(indexed) + (0 if anonymous else 1):
        classes.append("log-arity")
    if not anonymous and emitter["topic0_literal"] != topic0_of(signature(name, inputs)):
        classes.append("topic0")
    names = [p["name"] for p in emitter["params"]]
    if len(names) != len(inputs):
        classes.append("parameter-count")
        return classes
    topic_values = emitter["topic_args"]
    if anonymous and emitter["topic0_literal"] is not None:
        topic_values = [emitter["topic0_literal"]] + emitter["topic_args"]
    if len(topic_values) == len(indexed) and topic_values != [names[n] for n in indexed]:
        classes.append("indexed-order")
    if emitter["data_bytes"] != 32 * len(data):
        classes.append("data-length")
    elif emitter["data_args"] != [names[n] for n in data]:
        classes.append("data-order")
    return classes


def _abi_type(entry: dict) -> str | None:
    kind = entry.get("type")
    if not isinstance(kind, str):
        return None
    if kind.startswith("tuple"):
        parts = [_abi_type(c) for c in entry.get("components") or []]
        if None in parts:
            return None
        return "(" + ",".join(parts) + ")" + kind[len("tuple"):]
    return kind


def abi_events(output: dict) -> dict[str, list[dict]]:
    events: dict[str, list[dict]] = {}
    for entry in output.get("abi") or []:
        if isinstance(entry, dict) and entry.get("type") == "event":
            inputs = [{"type": _abi_type(i), "indexed": bool(i.get("indexed")), "name": i.get("name", "")}
                      for i in entry.get("inputs") or []]
            events.setdefault(entry.get("name"), []).append(
                {"inputs": inputs, "anonymous": bool(entry.get("anonymous"))})
    return events


