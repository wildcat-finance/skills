class Refusal(Exception):
    """A read or comparison that ends the command with exit 1."""

    def __init__(self, prefix: str, message: str):
        super().__init__(f"{prefix}: {message}")
        self.prefix = prefix


def read_failure(message: str) -> Refusal:
    return Refusal("read-failure", message)


def git_blob_id(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\x00" % len(data) + data).hexdigest()


def _safe_path(path: object) -> str:
    if not isinstance(path, str) or not _PATH.match(path) or ".." in path.split("/"):
        raise read_failure(f"unsafe path {path!r}")
    return path


def _safe_ref(ref: object) -> str:
    if not isinstance(ref, str) or not _COMMIT.match(ref):
        raise read_failure(f"ref {ref!r} is not a 40-hex commit")
    return ref


def deployment_paths(contract: str, address: str) -> tuple[str, str]:
    base = f"deployments/mainnet/{contract}-{address}"
    return f"{base}/standard-input.json", f"{base}/output.json"


