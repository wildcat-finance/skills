#!/usr/bin/env python3
"""Check Wildcat V1's assembly event emitters against their declarations.

    python3 scripts/emitter_declarations_v1.py build --from-git CLONE --out TABLE.json [--markdown TABLE.md]
    python3 scripts/emitter_declarations_v1.py check --from-git CLONE --table TABLE.json [--markdown TABLE.md] [--ref COMMIT]
    python3 scripts/emitter_declarations_v1.py check --from-https --table TABLE.json
    python3 scripts/emitter_declarations_v1.py crosscheck --solc SOLC

The V1 counterpart of scripts/emitter_declarations.py (#1361), for #1962. It
reuses that script's parser, type mapping and comparison, and its table's
row, mismatch, unreviewed and summary shapes. Three things differ, because V1
keeps no compiler input or output in its repository:

- The builds are Sourcify records, one per deployed contract that the
  accepted registry (`docs/kickoff/1359/targets.json`, row
  `wildcat-v1-ethereum-mainnet`) names. Each record's standard JSON input is
  pinned by the SHA-256 of its canonical form, the form the registry uses,
  and its compilation target's ABI by the SHA-256 of the ABI's canonical
  form. Where the registry pins a build input, the two digests must agree.
- Reach is contract-level. An emitter is reached by a build when a contract
  in the compilation target's own inheritance chain calls it. A call site in
  a library or a free function is not attributed; it is named instead.
- Each read `src/` file is bound to each build as equal, comments-only (the
  bytes differ only in comments and whitespace), differs, or absent.

`build` reads `wildcat-finance/wildcat-protocol` at `--ref` (default the
registry's V1 commit), every `.sol` file under `src/`, and the Sourcify
records the registry names, and writes the table. `check` takes the refs,
paths and digests from the committed table, refuses any read byte that
differs from it, regenerates the table and exits 1 on any byte difference.
`--ref` on `check` changes only the commit the `src/` bytes are read at.
`--sourcify-dir DIR` reads `DIR/<address>.json` Sourcify responses instead of
fetching them, under the same digest checks.

`crosscheck` needs the registry's solc. It compiles each registry-pinned
input with ABI-only output for every contract and compares each build's ABI
digest with the one that input yields. The market and controller builds are
instance records, so this is what ties their ABIs to the factory input the
registry pins. `build` and `check` never run a compiler.

Exit status: 0 when the table is written (`build`) or matches (`check`); 1 on
any refusal; 2 on a usage error. Each refusal line on stderr starts with one
prefix: `source-drift:` when read bytes, a Sourcify digest or the file list
differ from the table, `registry-difference:` when the registry no longer
names what the checker scans, `table-difference:` or `markdown-difference:`
when the source matches but the regenerated bytes differ, `read-failure:`
when a file, record or compiler run fails, `table-invalid:` when the
committed table is not a readable V1 table, and `abi-crosscheck:` when a
compiled ABI differs from its build's.

The scan is static text analysis. It runs no target code and makes no claim
about runtime behaviour, bytecode identity or capture completeness.
"""

