class _SourcifyRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        target = urllib.parse.urlsplit(newurl)
        if target.scheme != "https" or target.hostname != SOURCIFY_HOST:
            raise read_failure(f"redirect to {target.scheme}://{target.hostname} refused")
        return super().redirect_request(req, fp, code, msg, headers, newurl)


class SourcifyReader:
    """Fetch one Sourcify v2 record per address from the fixed host."""

    def __init__(self, opener=None):
        self.opener = opener or urllib.request.build_opener(_SourcifyRedirect)

    def record(self, address: str) -> dict:
        url = sourcify_url(_safe_address(address))
        try:
            with self.opener.open(url, timeout=core.HTTPS_TIMEOUT_SECONDS * 4) as response:  # phylax: allow url: fixed host, validated address, digest-verified
                final = urllib.parse.urlsplit(response.geturl())
                if final.scheme != "https" or final.hostname != SOURCIFY_HOST:
                    raise read_failure(f"Sourcify record for {address} was served from {final.hostname}")
                data = response.read(MAX_RECORD_BYTES + 1)
        except Refusal:
            raise
        except (OSError, ValueError) as err:
            raise read_failure(f"Sourcify record for {address} could not be fetched: {type(err).__name__}") from None
        return _record_json(address, data)


class DirectorySourcifyReader:
    """Read saved Sourcify v2 responses named `<address>.json` from a directory."""

    def __init__(self, directory: str):
        self.directory = os.path.abspath(directory)

    def record(self, address: str) -> dict:
        path = os.path.join(self.directory, _safe_address(address) + ".json")
        try:
            with open(path, "rb") as fh:
                data = fh.read(MAX_RECORD_BYTES + 1)
        except OSError as err:
            raise read_failure(f"Sourcify record for {address} cannot be read: {type(err).__name__}") from None
        return _record_json(address, data)


def _safe_address(address: object) -> str:
    if not isinstance(address, str) or not _ADDRESS.match(address):
        raise read_failure(f"address {address!r} is not a lowercase 20-byte hex address")
    return address


def _record_json(address: str, data: bytes) -> dict:
    if len(data) > MAX_RECORD_BYTES:
        raise read_failure(f"Sourcify record for {address} exceeds the {MAX_RECORD_BYTES}-byte cap")
    try:
        record = json.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError):
        raise read_failure(f"Sourcify record for {address} is not JSON") from None
    if not isinstance(record, dict):
        raise read_failure(f"Sourcify record for {address} is not a JSON object")
    return record


# --- registry --------------------------------------------------------------


def load_registry(root: str = ROOT) -> dict:
    """Return the V1 facts this checker scans, read from the accepted registry."""
    path = os.path.join(root, REGISTRY_PATH)
    try:
        with open(path, "rb") as fh:
            registry = json.loads(fh.read().decode("utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as err:
        raise Refusal("registry-difference", f"{REGISTRY_PATH} cannot be read: {type(err).__name__}") from None
    rows = registry.get("targets") if isinstance(registry, dict) else None
    row = next((r for r in rows or [] if isinstance(r, dict) and r.get("id") == REGISTRY_ROW), None)
    if row is None:
        raise Refusal("registry-difference", f"{REGISTRY_PATH} has no row {REGISTRY_ROW}")
    try:
        source, deployment = row["source"], row["deployment"]
        if source["repository"] != f"https://github.com/{REPOSITORY}":
            raise Refusal("registry-difference", f"the V1 row names repository {source['repository']}")
        commit = core._safe_ref(source["commit"])
        emitter_paths = sorted(p["path"] for p in source["emitter_paths"])
        if emitter_paths != sorted(EMITTER_FILES):
            raise Refusal("registry-difference", f"the V1 row names emitter paths {emitter_paths}; "
                                                 f"this checker scans {sorted(EMITTER_FILES)}")
        pinned_inputs = {i["compilation_target"]: i["sha256"] for i in source["build_inputs"]}
        contracts = {c["address"]: c for c in deployment["contracts"]}
        builds = []
        for role, instances in BUILD_ROLES:
            if instances:
                listed = deployment["instances"][instances]
                address = listed[0]
                count = len(listed)
            else:
                matches = [a for a, c in contracts.items() if c["role"] == role]
                if len(matches) != 1:
                    raise Refusal("registry-difference", f"the V1 row lists {len(matches)} contracts with role {role}")
                address, count = matches[0], 1
            entry = contracts.get(address)
            if entry is None:
                raise Refusal("registry-difference", f"the V1 row lists {address} as a {role} but not as a contract")
            builds.append({
                "role": role, "address": _safe_address(address), "instances": count,
                "registry_name": entry["name"],
                "source_commit": core._safe_ref(entry["code_match"]["source_commit"]),
            })
        compiler = source["compiler"]["solc"]
    except Refusal:
        raise
    except (KeyError, TypeError, IndexError):
        raise Refusal("registry-difference", f"the {REGISTRY_ROW} row lacks a field this checker reads") from None
    return {"path": REGISTRY_PATH, "row": REGISTRY_ROW, "commit": commit, "compiler": compiler,
            "emitter_paths": emitter_paths, "pinned_inputs": pinned_inputs, "builds": builds}


# --- builds ----------------------------------------------------------------


def read_builds(reader, registry: dict) -> list[dict]:
    """Fetch and digest each registry build's Sourcify record."""
    builds = []
    for spec in registry["builds"]:
        record = reader.record(spec["address"])
        builds.append(parse_record(spec, record, registry))
    return builds


def parse_record(spec: dict, record: dict, registry: dict) -> dict:
    address = spec["address"]
    try:
        if str(record["address"]).lower() != address or str(record["chainId"]) != str(CHAIN_ID):
            raise read_failure(f"Sourcify record for {address} names another contract or chain")
        standard_input = record["stdJsonInput"]
        compilation = record["compilation"]
        fqn = compilation["fullyQualifiedName"]
        match = _FQN.match(fqn or "")
        if not match:
            raise read_failure(f"Sourcify record for {address} has compilation target {fqn!r}")
        path, name = match.group(1), match.group(2)
        abi = record["stdJsonOutput"]["contracts"][path][name]["abi"]
        sources = standard_input["sources"]
        contents = {p: s["content"] for p, s in sources.items()}
        if not all(isinstance(c, str) for c in contents.values()):
            raise TypeError
        version = compilation["compilerVersion"]
        full_match = record.get("match")
    except Refusal:
        raise
    except (KeyError, TypeError, AttributeError):
        raise read_failure(f"Sourcify record for {address} lacks a field this checker reads") from None
    if sum(len(c) for c in contents.values()) > MAX_SOURCE_BYTES:
        raise read_failure(f"Sourcify sources for {address} exceed the {MAX_SOURCE_BYTES}-byte cap")
    input_digest = sha256(canonical(standard_input))
    pinned = registry["pinned_inputs"].get(name)
    if pinned is not None and pinned != input_digest:
        raise Refusal("source-drift", f"Sourcify input for {name} at {address} has SHA-256 {input_digest}; "
                                      f"the registry pins {pinned}")
    return {
        "contract": name, "role": spec["role"], "address": address,
        "registry_name": spec["registry_name"], "instances": spec["instances"],
        "source_commit": spec["source_commit"], "fully_qualified_name": fqn,
        "compiler": version, "match": full_match,
        "standard_input": input_url(address), "standard_input_sha256": input_digest,
        "registry_build_input": pinned is not None,
        "abi": abi_url(address), "abi_sha256": sha256(canonical(abi)),
        "_sources": contents, "_abi": abi, "_input": standard_input,
    }


# --- analysis --------------------------------------------------------------


class Unit:
    """One set of sources, masked once, with its contract definitions."""

    def __init__(self, sources: dict[str, str]):
        self.sources = sources
        self.masked = {path: core.mask(text) for path, text in sources.items()}
        self.defs = _definitions(self.masked)
        self.spans = [(d["start"], d["end"], d["kind"], name, d["path"])
                      for name, items in self.defs.items() for d in items]

    def owner(self, path: str, offset: int) -> tuple | None:
        inside = [s for s in self.spans if s[4] == path and s[0] <= offset <= s[1]]
        return max(inside, key=lambda s: s[0]) if inside else None


def _definitions(masked: dict[str, str]) -> dict[str, list[dict]]:
    """Map each contract, interface and library name to its definitions."""
    found: dict[str, list[dict]] = {}
    for path in sorted(masked):
        clean = masked[path]
        for m in _DEFINITION.finditer(clean):
            end = core._close(clean, m.end() - 1, "{", "}")
            header = m.group(3).strip()
            bases = []
            if header.startswith("is") and (len(header) == 2 or not (header[2].isalnum() or header[2] == "_")):
                for item in core.split_args(header[2:]):
                    base = re.match(r"\s*([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*)", item)
                    bases.append(base.group(1).split(".")[-1] if base else None)
            found.setdefault(m.group(2), []).append({
                "path": path, "kind": m.group(1), "start": m.start(),
                "end": len(clean) if end is None else end, "bases": bases,
            })
    return found


def inheritance_chain(unit: Unit, target: str) -> tuple[set[str], list[str]]:
    """(contract names in target's inheritance chain, unresolved base names).

    A build's input is a whole compilation unit, so every base must resolve
    to exactly one definition in it.
    """
    chain, pending, unresolved = set(), [target], []
    while pending:
        name = pending.pop()
        if name in chain:
            continue
        found = unit.defs.get(name, [])
        if len(found) != 1 or None in found[0]["bases"]:
            unresolved.append(str(name))
            continue
        chain.add(name)
        pending.extend(found[0]["bases"])
    return chain, sorted(set(unresolved))


def call_sites(unit: Unit, emitter: str, emitter_path: str) -> list[dict]:
    """Every call of emitter outside its own file, with the definition holding it."""
    call = re.compile(r"\b" + re.escape(emitter) + r"\s*\(")
    sites = []
    for path in sorted(unit.masked):
        if path == emitter_path:
            continue
        clean = unit.masked[path]
        for m in call.finditer(clean):
            owner = unit.owner(path, m.start())
            sites.append({"at": f"{path}:{core._line(clean, m.start())}",
                          "owner": owner[3] if owner else None, "kind": owner[2] if owner else None})
    return sites


class Reach:
    """Contract-level reach over each build's own sources."""

    def __init__(self, builds: list[dict]):
        self.builds = builds
        self.units = {b["contract"]: Unit(b["_sources"]) for b in builds}
        self.unattributed: dict[str, list[str]] = {}
        self.unresolved: dict[str, list[str]] = {}
        self.chains = {}
        for b in builds:
            name = b["contract"]
            self.chains[name], missing = inheritance_chain(self.units[name], name)
            if missing:
                self.unresolved[name] = missing

    def __call__(self, emitter: dict) -> list[str]:
        reached, loose = [], set()
        for b in self.builds:
            if emitter["path"] not in b["_sources"]:
                continue
            for site in call_sites(self.units[b["contract"]], emitter["emitter"], emitter["path"]):
                if site["kind"] == "contract" and site["owner"] in self.chains[b["contract"]]:
                    reached.append(b["contract"])
                elif site["kind"] != "contract":
                    loose.add(f"{site['at']} in {b['contract']}'s input")
        if loose:
            self.unattributed[emitter["emitter"]] = sorted(loose)
        return sorted(set(reached))


def binding(git_text: str, build_text: str | None) -> str:
    if build_text is None:
        return "absent"
    if build_text == git_text:
        return "equal"
    if "".join(core.mask(build_text).split()) == "".join(core.mask(git_text).split()):
        return "comments-only"
    return "differs"


_EMIT = re.compile(r"\bemit\s+((?:[A-Za-z_]\w*\.)*)([A-Za-z_]\w*)\s*\(")


def _scope(defs: dict[str, list[dict]], owner: str) -> tuple[set[str], list[str]]:
    """(names in owner's inheritance chain found under src/, names defined more than once)."""
    chain, pending, ambiguous = set(), [owner], []
    while pending:
        name = pending.pop()
        if name is None or name in chain:
            continue
        found = defs.get(name, [])
        if len(found) > 1:
            ambiguous.append(name)
            continue
        chain.add(name)
        if found:
            pending.extend(found[0]["bases"])
    return chain, sorted(set(ambiguous))


def resolve_emit_sites(unit: Unit, declarations: list[dict]) -> tuple[dict[str, list[str]], list[dict]]:
    """Attribute each Solidity `emit` under src/ to the declaration it names.

    An unqualified name resolves through the emitting contract's inheritance
    chain, a qualified one to the named contract or interface. A base defined
    outside src/ is outside the declaration scope and adds no candidate.
    Returns ({declaration key: sites}, unresolved sites).
    """
    by_key: dict[str, list[str]] = {}
    unresolved = []
    for path in sorted(unit.masked):
        clean = unit.masked[path]
        for m in _EMIT.finditer(clean):
            at, name = f"{path}:{core._line(clean, m.start())}", m.group(2)
            span = unit.owner(path, m.start())
            owner = span[3] if span else None
            qualifier = m.group(1).rstrip(".").split(".")[-1] if m.group(1) else None
            ambiguous = []
            if qualifier:
                owners = {qualifier}
            elif owner:
                owners, ambiguous = _scope(unit.defs, owner)
            else:
                owners = set()
            candidates = [d for d in declarations if d["name"] == name
                          and (d["qualified"].split(".")[0] in owners or d["qualified"].startswith("<file>."))]
            if len(candidates) > 1:
                close = core._close(clean, m.end() - 1, "(", ")")
                count = len(core.split_args(clean[m.end():close])) if close is not None else -1
                candidates = [d for d in candidates if len(d["inputs"]) == count]
            if len(candidates) != 1 or ambiguous:
                reason = (f"inheritance names {', '.join(ambiguous)} more than once" if ambiguous
                          else f"resolves to {len(candidates)} declarations under src/")
                unresolved.append({"kind": "emit-site", "name": name, "at": at, "reason": reason})
                continue
            d = candidates[0]
            by_key.setdefault(d["qualified"] + "@" + d["at"], []).append(at)
    return by_key, unresolved


def _shape(inputs: list[dict], anonymous: bool) -> tuple:
    return tuple((i["type"], i["indexed"]) for i in inputs), anonymous


def declaration_disagreements(declarations: list[dict], emitted: dict[str, list[str]],
                              assembly: dict[str, list[str]], builds: list[dict]) -> list[dict]:
    """Same-named declarations whose signature, indexed positions or anonymity differ.

    Each variant names the builds whose ABI carries an event of that name
    with exactly its types, indexed flags and anonymity.
    """
    views = {b["contract"]: core.abi_events({"abi": b["_abi"]}) for b in builds}
    groups: dict[str, list[dict]] = {}
    for d in declarations:
        groups.setdefault(d["name"], []).append(d)
    found = []
    for name in sorted(groups):
        variants = []
        for d in groups[name]:
            key = d["qualified"] + "@" + d["at"]
            shape = _shape(d["inputs"], d["anonymous"])
            variants.append({
                "declaration": d["qualified"], "declared_at": d["at"],
                "signature": core.signature(name, d["inputs"]),
                "indexed_positions": [n for n, i in enumerate(d["inputs"]) if i["indexed"]],
                "anonymous": d["anonymous"],
                "assembly_emitters": assembly.get(key, []),
                "solidity_emit_sites": emitted.get(key, []),
                "in_abi_of": sorted(c for c, events in views.items()
                                    if any(_shape(e["inputs"], e["anonymous"]) == shape for e in events.get(name, []))),
            })
        shapes = {(v["signature"], tuple(v["indexed_positions"]), v["anonymous"]) for v in variants}
        if len(shapes) > 1:
            found.append({"name": name, "variants": variants})
    return found


def stray_sites(unit: Unit) -> list[dict]:
    """Assembly log sites and emit_ functions outside the registry's emitter paths."""
    found = []
    for path in sorted(unit.masked):
        if path in EMITTER_FILES:
            continue
        clean = unit.masked[path]
        for m in _LOG_SITE.finditer(clean):
            found.append({"kind": "log-site", "name": m.group(0).rstrip("( "), "at": f"{path}:{core._line(clean, m.start())}",
                          "reason": "log site outside the registry's emitter paths"})
        for m in _EMITTER_DEF.finditer(clean):
            found.append({"kind": "emitter", "name": m.group(1), "at": f"{path}:{core._line(clean, m.start())}",
                          "reason": "emit_ function outside the registry's emitter paths"})
    return found


