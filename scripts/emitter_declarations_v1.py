def assemble(files: list[tuple[dict, bytes]], commit: str, registry: dict, builds: list[dict]) -> dict:
    total = sum(len(data) for _entry, data in files)
    if total > core.MAX_TOTAL_BYTES:
        raise read_failure(f"{total} bytes read, over the {core.MAX_TOTAL_BYTES}-byte total cap")
    sources = {e["path"]: core._decode(e["path"], data) for e, data in files}
    deployments = {b["contract"]: {"input": {"sources": {p: {"content": c} for p, c in b["_sources"].items()}},
                                   "output": {"abi": b["_abi"]}} for b in builds}
    reach = Reach(builds)
    body = core.scan(sources, deployments, EMITTER_FILES, reach=reach)
    for row in body["rows"]:
        loose = reach.unattributed.get(row["emitter"])
        if loose:
            row["notes"].append("call sites " + ", ".join(loose) + " are in a library or free function; "
                                "reach through them is not attributed")
    for emitter, loose in sorted(reach.unattributed.items()):
        body["unreviewed"].append({"kind": "reach", "name": emitter, "at": loose[0],
                                   "reason": "call site in a library or free function; reach not attributed"})
    for contract, missing in sorted(reach.unresolved.items()):
        body["unreviewed"].append({"kind": "reach", "name": contract, "at": f"build {contract}",
                                   "reason": "inheritance names " + ", ".join(missing) + " do not resolve to one definition"})
    resolver = core.TypeResolver(sources)
    declarations = []
    for path in sorted(sources):
        declarations += core.parse_declarations(path, sources[path], resolver)[0]
    unit = Unit(sources)
    emitted, unresolved = resolve_emit_sites(unit, declarations)
    assembly: dict[str, list[str]] = {}
    for row in body["rows"]:
        assembly.setdefault(row["declaration"] + "@" + row["declared_at"], []).append(row["emitter"])
    body["unreviewed"] += stray_sites(unit) + unresolved
    body["unreviewed"].sort(key=lambda u: (u["at"], u["kind"], u["name"]))
    for item in body["declarations_without_emitter"]:
        item["solidity_emit_sites"] = emitted.get(item["declaration"] + "@" + item["declared_at"], [])
    body["declaration_disagreements"] = declaration_disagreements(declarations, emitted, assembly, builds)
    entries = []
    for e, _data in sorted(files, key=lambda f: f[0]["path"]):
        entry = dict(e)
        entry["in_builds"] = {b["contract"]: binding(sources[e["path"]], b["_sources"].get(e["path"]))
                              for b in sorted(builds, key=lambda b: b["contract"])}
        entries.append(entry)
    summary = body["summary"]
    summary["unreviewed"] = len(body["unreviewed"])
    summary["binding_differs"] = sorted(e["path"] for e in entries if "differs" in e["in_builds"].values())
    summary["binding_comments_only"] = sorted(
        e["path"] for e in entries if "comments-only" in e["in_builds"].values())
    summary["non_emitting_declarations"] = sum(
        not item["solidity_emit_sites"] for item in body["declarations_without_emitter"])
    summary["unreached_rows"] = sum(not r["reached_by"] for r in body["rows"])
    summary["declaration_disagreements"] = len(body["declaration_disagreements"])
    body["schema"] = SCHEMA
    body["source"] = {
        "repository": REPOSITORY, "commit": commit, "build_origin": "sourcify", "chain_id": CHAIN_ID,
        "declaration_scope": "every .sol file under src/ at commit",
        "emitter_files": list(EMITTER_FILES),
        "registry": {k: registry[k] for k in ("path", "row", "commit", "compiler", "emitter_paths")},
        "deployments": [{k: v for k, v in b.items() if not k.startswith("_")} for b in builds],
        "files": entries,
    }
    return body


def read_sources(reader, ref: str) -> list[tuple[dict, bytes]]:
    listed = reader.list_sources(ref)
    files = []
    for path in sorted(listed):
        data = reader.read(ref, path)
        if core.git_blob_id(data) != listed[path]:
            raise read_failure(f"{path} at {ref}: bytes do not hash to listed blob {listed[path]}")
        files.append((core._entry(path, ref, "source", data), data))
    return files


def load_table(path: str) -> tuple[bytes, dict]:
    try:
        with open(path, "rb") as fh:
            raw = fh.read(core.MAX_TOTAL_BYTES + 1)
    except OSError as err:
        raise Refusal("table-invalid", f"{path} cannot be read: {type(err).__name__}") from None
    try:
        table = json.loads(raw.decode("utf-8"))
        source = table["source"]
        files = source["files"]
        ok = (table.get("schema") == SCHEMA and source.get("repository") == REPOSITORY
              and source.get("build_origin") == "sourcify" and isinstance(files, list)
              and all(isinstance(f, dict) and {"path", "ref", "role", "blob", "bytes", "sha256"} <= set(f)
                      for f in files)
              and isinstance(source["deployments"], list)
              and all({"address", "standard_input_sha256", "abi_sha256"} <= set(d) for d in source["deployments"]))
        core._safe_ref(source["commit"])
        for f in files:
            core._safe_path(f["path"])
            core._safe_ref(f["ref"])
        for d in source["deployments"]:
            _safe_address(d["address"])
    except (UnicodeDecodeError, json.JSONDecodeError, KeyError, TypeError, AttributeError, Refusal):
        ok = False
    if not ok:
        raise Refusal("table-invalid", f"{path} is not a V1 {SCHEMA} table")
    return raw, table


def read_table_sources(reader, table: dict, source_ref: str | None) -> tuple[list[tuple[dict, bytes]], list[str]]:
    drift, files = [], []
    table_sources = {f["path"] for f in table["source"]["files"]}
    read_ref = source_ref or table["source"]["commit"]
    listed = None
    if reader.list_sources is not None:
        listed = set(reader.list_sources(read_ref))
        drift += [f"{p} is present at {read_ref} and absent from the table" for p in sorted(listed - table_sources)]
        drift += [f"{p} is in the table and absent at {read_ref}" for p in sorted(table_sources - listed)]
    for f in table["source"]["files"]:
        if listed is not None and f["path"] not in listed:
            continue
        data = reader.read(read_ref, f["path"])
        seen = core._entry(f["path"], read_ref, "source", data)
        if (seen["bytes"], seen["sha256"], seen["blob"]) != (f["bytes"], f["sha256"], f["blob"]):
            drift.append(f"{f['path']} at {read_ref}: sha256 {f['sha256']} -> {seen['sha256']}, "
                         f"bytes {f['bytes']} -> {seen['bytes']}")
        files.append(({**seen, "ref": f["ref"]}, data))
    return files, drift


def build_drift(table: dict, builds: list[dict]) -> list[str]:
    drift = []
    committed = {d["address"]: d for d in table["source"]["deployments"]}
    for b in builds:
        d = committed.get(b["address"])
        if d is None:
            drift.append(f"build {b['contract']} at {b['address']} is absent from the table")
            continue
        for key in ("standard_input_sha256", "abi_sha256"):
            if d[key] != b[key]:
                drift.append(f"build {b['contract']} at {b['address']}: {key} {d[key]} -> {b[key]}")
    for address in sorted(set(committed) - {b["address"] for b in builds}):
        drift.append(f"build at {address} is in the table and no longer named by the registry")
    return drift


def render_markdown(table: dict) -> str:
    def cell(value) -> str:
        text = value if isinstance(value, str) else json.dumps(value, sort_keys=True)
        return text.replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")

    source, summary = table["source"], table["summary"]
    lines = [
        "# Wildcat V1 emitter declarations", "",
        f"Schema `{table['schema']}`. Source `{source['repository']}` at commit `{source['commit']}`; "
        f"builds are Sourcify records on chain {source['chain_id']}, bound to the registry row "
        f"`{source['registry']['row']}` in `{source['registry']['path']}`.", "",
        "Mismatch classes: " + ", ".join(f"`{c}`" for c in core.MISMATCH_CLASSES)
        + "; a class found against a build's ABI is prefixed `abi:<contract>:`.", "",
        "## Regenerating this table", "",
        "```sh", f"python3 scripts/emitter_declarations_v1.py build --from-git <clone> "
        f"--out {TABLE_PATH} --markdown {MARKDOWN_PATH}", "```", "",
        "Verify without writing:", "",
        "```sh", f"python3 scripts/emitter_declarations_v1.py check --from-git <clone> "
        f"--table {TABLE_PATH} --markdown {MARKDOWN_PATH}", "```", "",
        f"Tie each build's ABI to the inputs the registry pins, with the registry's compiler "
        f"`{source['registry']['compiler']}`:", "",
        "```sh", "python3 scripts/emitter_declarations_v1.py crosscheck --solc <solc>", "```", "",
        "## Scope and limits", "", STATIC_NOTE, "", BUILD_NOTE, "", PIN_NOTE, "", REACH_NOTE, "",
        "## Builds", "",
        "| Contract | Role | Address | Instances | Source commit | Compiler | Registry input | Standard input SHA-256 | ABI SHA-256 |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for d in source["deployments"]:
        lines.append(f"| {d['contract']} | {d['role']} | `{d['address']}` | {d['instances']} | `{d['source_commit'][:8]}` "
                     f"| `{d['compiler']}` | {'pinned' if d['registry_build_input'] else 'not pinned'} "
                     f"| `{d['standard_input_sha256']}` | `{d['abi_sha256']}` |")
    lines += ["", "## Summary", "", "| Count | Value | Meaning |", "| --- | --- | --- |"]
    for key in sorted(summary):
        lines.append(f"| {cell(key)} | {cell(summary[key])} | {cell(SUMMARY_MEANINGS.get(key, 'see the JSON'))} |")
    lines += ["", "## Rows", "",
              "| Emitter | Declaration | Signature | topic0 | logN | Indexed | Data bytes | ABI checked | Reached by | Status | Classes | Notes |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in table["rows"]:
        lines.append("| " + " | ".join([
            f"`{r['emitter']}` ({cell(r['emitter_at'])})", f"`{r['declaration']}` ({cell(r['declared_at'])})",
            f"`{cell(r['signature'])}`", f"`{cell(r['topic0'])}`", cell(r["log_arity"]),
            cell(r["indexed_positions"]), cell(r["data_bytes"]), cell(", ".join(r["abi_checked"]) or "none"),
            cell(", ".join(r["reached_by"]) or "none"), cell(r["status"]),
            cell(", ".join(r["classes"]) or "none"), cell("; ".join(r["notes"]) or "none"),
        ]) + " |")
    for title, key, columns in (
        ("Mismatches", "mismatches", ("emitter", "declaration", "declared_at", "classes")),
        ("Unreviewed", "unreviewed", ("kind", "name", "at", "reason")),
    ):
        lines += ["", f"## {title}", ""]
        if not table[key]:
            lines.append("None.")
            continue
        lines.append("| " + " | ".join(columns) + " |")
        lines.append("| " + " | ".join("---" for _ in columns) + " |")
        for item in table[key]:
            lines.append("| " + " | ".join(cell(", ".join(item[c]) if isinstance(item[c], list) else item[c])
                                           for c in columns) + " |")
    lines += ["", "## Same-named declarations that disagree", "",
              "Each event below is declared more than once, with different signatures, indexed positions or "
              "anonymity. A decoder built from a variant that nothing emits computes a topic0 or layout "
              "that no deployed log carries. Every row above still compares its emitter with each "
              "same-named declaration separately.", ""]
    if not table["declaration_disagreements"]:
        lines.append("None.")
    else:
        lines += ["| Event | Declaration | Declared at | Signature | Indexed | Anonymous | Emitted by | In the ABI of |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for group in table["declaration_disagreements"]:
        for v in group["variants"]:
            emitted_by = ", ".join([f"`{e}`" for e in v["assembly_emitters"]] + v["solidity_emit_sites"])
            lines.append(f"| `{group['name']}` | {cell(v['declaration'])} | {cell(v['declared_at'])} "
                         f"| `{cell(v['signature'])}` | {cell(v['indexed_positions'])} | {cell(v['anonymous'])} "
                         f"| {cell(emitted_by or 'nothing')} | {cell(', '.join(v['in_abi_of']) or 'no build')} |")
    lines += ["", "## Declarations with no assembly emitter", "",
              "Each is either emitted by a Solidity `emit` statement, whose log the compiler derives from the "
              "declaration, or emitted nowhere under `src/`. An emit site is attributed through the emitting "
              "contract's inheritance chain, so a same-named declaration the contract does not inherit gets "
              "none of its sites.", ""]
    if not table["declarations_without_emitter"]:
        lines.append("None.")
    else:
        lines.append("| Declaration | Declared at | Signature | Solidity emit sites |")
        lines.append("| --- | --- | --- | --- |")
        for item in table["declarations_without_emitter"]:
            lines.append(f"| {cell(item['declaration'])} | {cell(item['declared_at'])} | {cell(item['signature'])} "
                         f"| {cell(', '.join(item['solidity_emit_sites']) or 'none: non-emitting')} |")
    unreached = [r for r in table["rows"] if not r["reached_by"]]
    lines += ["", "## Not reached by any deployed build", "",
              "A row here has an emitter that no listed build's compilation target calls through its own "
              "inheritance chain. It keeps its row and its comparison.", ""]
    if not unreached:
        lines.append("None.")
    else:
        lines.append("| Emitter | Declaration | Declared at | Status |")
        lines.append("| --- | --- | --- | --- |")
        for r in unreached:
            lines.append(f"| `{r['emitter']}` ({cell(r['emitter_at'])}) | `{r['declaration']}` "
                         f"| {cell(r['declared_at'])} | {cell(r['status'])} |")
    lines += ["", "## Source files", "", "| Path | Blob | Bytes | SHA-256 | Binding |",
              "| --- | --- | --- | --- | --- |"]
    for f in source["files"]:
        builds = ", ".join(f"{k}={v}" for k, v in sorted(f["in_builds"].items()))
        lines.append(f"| `{f['path']}` | `{f['blob']}` | {f['bytes']} | `{f['sha256']}` | {cell(builds)} |")
    lines.append("")
    return "\n".join(lines)


# --- compiler cross-check --------------------------------------------------


SOLC_TIMEOUT_SECONDS = 600


def _solc(solc: str, arguments: list[str], stdin: bytes | None = None) -> bytes:
    try:
        result = subprocess.run(  # phylax: allow subprocess: fixed argv list naming a user-supplied solc binary, no shell
            [solc, *arguments], input=stdin, capture_output=True, timeout=SOLC_TIMEOUT_SECONDS, check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as err:
        raise read_failure(f"solc did not complete: {type(err).__name__}") from None
    if result.returncode != 0:
        raise read_failure(f"solc exited {result.returncode}")
    return result.stdout


def crosscheck(sourcify, solc: str, root: str = ROOT) -> tuple[list[str], list[str]]:
    """Compile each registry-pinned input for ABI only and compare every build it covers.

    Returns (result lines, problem lines). A build no pinned input compiles
    is named as not cross-checked, never as agreeing.
    """
    registry = load_registry(root)
    builds = read_builds(sourcify, registry)
    version = _solc(solc, ["--version"]).decode("utf-8", "replace")
    if registry["compiler"] not in version:
        return [], [f"abi-crosscheck: solc reports {version.strip().splitlines()[-1]!r}, "
                    f"not the registry's {registry['compiler']}"]
    with open(solc, "rb") as fh:
        binary = sha256(fh.read())
    lines, problems = [f"abi-crosscheck: solc {registry['compiler']}, binary SHA-256 {binary}"], []
    covered, failed = set(), set()
    for pinned in (b for b in builds if b["registry_build_input"]):
        request = json.loads(json.dumps(pinned["_input"]))
        request.setdefault("settings", {})["outputSelection"] = {"*": {"*": ["abi"]}}
        output = json.loads(_solc(solc, ["--standard-json"], canonical(request)).decode("utf-8"))
        errors = [e for e in output.get("errors", []) if e.get("severity") == "error"]
        if errors:
            problems.append(f"abi-crosscheck: the {pinned['contract']} input does not compile: {len(errors)} errors")
            continue
        for b in builds:
            path, name = b["fully_qualified_name"].split(":")
            entry = output.get("contracts", {}).get(path, {}).get(name)
            if entry is None:
                continue
            digest = sha256(canonical(entry["abi"]))
            label = f"{b['contract']} ABI from the {pinned['contract']} input ({pinned['standard_input_sha256'][:12]})"
            if digest == b["abi_sha256"]:
                lines.append(f"abi-crosscheck: {label} equals its build's, {digest}")
                covered.add(b["contract"])
            else:
                problems.append(f"abi-crosscheck: {label} is {digest}; its build carries {b['abi_sha256']}")
                failed.add(b["contract"])
    for b in builds:
        if b["contract"] not in covered | failed:
            lines.append(f"abi-crosscheck: {b['contract']} is compiled by no registry-pinned input; not cross-checked")
    return lines, problems


