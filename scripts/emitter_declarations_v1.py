def run_build(reader, sourcify, out: str, markdown: str | None, ref: str | None, root: str = ROOT) -> dict:
    registry = load_registry(root)
    if reader.list_sources is None:
        raise Refusal("read-failure", "a V1 build reads src/ from a clone; use --from-git")
    commit = ref or registry["commit"]
    files = read_sources(reader, commit)
    builds = read_builds(sourcify, registry)
    table = assemble(files, commit, registry, builds)
    core.atomic_write(out, core.serialize(table))
    if markdown:
        core.atomic_write(markdown, render_markdown(table).encode("utf-8"))
    return table


def run_check(reader, sourcify, table_path: str, markdown: str | None, source_ref: str | None,
              root: str = ROOT) -> list[str]:
    raw, committed = load_table(table_path)
    registry = load_registry(root)
    files, drift = read_table_sources(reader, committed, source_ref)
    builds = read_builds(sourcify, registry)
    drift += build_drift(committed, builds)
    if drift:
        return [f"source-drift: {line}" for line in drift] + [
            f"source-drift: {len(drift)} source differences from {table_path}; the table was not regenerated"]
    table = assemble(files, committed["source"]["commit"], registry, builds)
    regenerated = core.serialize(table)
    problems = []
    if regenerated != raw:
        problems.append(f"table-difference: {table_path} differs from the table regenerated from matching source")
        problems += [f"table-difference: {line}" for line in core._diff_lines(raw, regenerated, table_path)]
    if markdown:
        try:
            with open(markdown, "rb") as fh:
                committed_md = fh.read(core.MAX_TOTAL_BYTES + 1)
        except OSError as err:
            return problems + [f"markdown-difference: {markdown} cannot be read: {type(err).__name__}"]
        rendered = render_markdown(table).encode("utf-8")
        if rendered != committed_md:
            problems.append(f"markdown-difference: {markdown} differs from its rendering of the table")
            problems += [f"markdown-difference: {line}" for line in core._diff_lines(committed_md, rendered, markdown)]
    return problems


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    subparsers = parser.add_subparsers(dest="command", required=True)
    build = subparsers.add_parser("build", help="regenerate the V1 emitter table")
    check = subparsers.add_parser("check", help="compare a regenerated table with the committed one")
    for sub in (build, check):
        origin = sub.add_mutually_exclusive_group(required=True)
        origin.add_argument("--from-git", metavar="CLONE", help="read src/ from a local wildcat-protocol clone")
        origin.add_argument("--from-https", action="store_true", help=f"read src/ from {core.ALLOWED_HOST}")
        sub.add_argument("--markdown", metavar="PATH", help="the rendered Markdown table")
        sub.add_argument("--sourcify-dir", metavar="DIR", help="read saved Sourcify responses from DIR")
        sub.add_argument("--ref", type=core._commit, help="read src/ at this commit")
    build.add_argument("--out", required=True, metavar="PATH", help="where to write the JSON table")
    check.add_argument("--table", required=True, metavar="PATH", help="the committed JSON table")
    cross = subparsers.add_parser("crosscheck", help="compile the registry-pinned inputs and compare build ABIs")
    cross.add_argument("--solc", required=True, metavar="PATH", help="the registry's solc version")
    cross.add_argument("--sourcify-dir", metavar="DIR", help="read saved Sourcify responses from DIR")
    return parser


def main(argv: list[str] | None = None, reader=None, sourcify=None, root: str = ROOT) -> int:
    args = build_parser().parse_args(argv)
    if reader is None and args.command != "crosscheck":
        reader = HttpsReader() if args.from_https else core.GitReader(args.from_git)
    if sourcify is None:
        sourcify = DirectorySourcifyReader(args.sourcify_dir) if args.sourcify_dir else SourcifyReader()
    try:
        if args.command == "crosscheck":
            lines, problems = crosscheck(sourcify, args.solc, root)
            for line in lines + problems:
                print(line, file=sys.stderr)
            return 1 if problems else 0
        if args.command == "build":
            table = run_build(reader, sourcify, args.out, args.markdown, args.ref, root)
            s = table["summary"]
            print(f"build: {s['emitters']} emitters, {s['rows']} rows, {s['mismatch_rows']} mismatch rows, "
                  f"{s['unreviewed']} unreviewed; wrote {args.out}", file=sys.stderr)
            return 0
        problems = run_check(reader, sourcify, args.table, args.markdown, args.ref, root)
    except Refusal as refusal:
        print(str(refusal), file=sys.stderr)
        return 1
    for line in problems:
        print(line, file=sys.stderr)
    if problems:
        return 1
    print(f"check: {args.table} regenerates exactly", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
