class HttpsReader(core.HttpsReader):
    """Read V1 blobs from raw.githubusercontent.com at a pinned commit."""

    @staticmethod
    def url(ref: str, path: str) -> str:
        ref, path = core._safe_ref(ref), core._safe_path(path)
