def canonical(value) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sourcify_url(address: str) -> str:
    return (f"https://{SOURCIFY_HOST}/server/v2/contract/{CHAIN_ID}/{address}"
            f"?fields={urllib.parse.quote(SOURCIFY_FIELDS, safe=',')}")


def abi_url(address: str) -> str:
    return f"https://{SOURCIFY_HOST}/server/v2/contract/{CHAIN_ID}/{address}?fields=stdJsonOutput"


def input_url(address: str) -> str:
    return f"https://{SOURCIFY_HOST}/server/v2/contract/{CHAIN_ID}/{address}?fields=stdJsonInput"


