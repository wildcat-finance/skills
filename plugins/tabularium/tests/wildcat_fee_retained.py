"""Qualified fee conformance over the two privately retained Wildcat releases.

The Alexandria owner checks both staging inventories and rebuilds each raw
release. Tabularium then builds explicit adapter 1.1.0 output and verifies all
generated bytes. Every present fee target must map; V2 collection must execute.
V1 collection and V2 Bips absence do not become positive observations. Returned
observations contain only release identifiers, digests and bounded outcomes.
"""

from __future__ import annotations

import json
from pathlib import Path
import shutil
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "scripts"))

from tabularium_lib import verifier
from tabularium_lib.core import TabulariumError
from tabularium_lib.keccak import keccak256
from tabularium_lib.wildcat_release import build_wildcat_canonical
from wildcat_batch_retained import (DIGEST_FILES, GENERATIONS, MAX_DOCUMENT_BYTES,
                                    RetainedGeneration, document, private_scratch,
                                    sha256_file)
from wildcat_fee_fixtures import BIPS, FEES, VENUES
from wildcat_v3_reports import EvidenceUnavailable

ADAPTER_VERSION = "1.1.0"
TARGET_TOPICS = frozenset("0x" + keccak256(value.encode()).hex() for value in (FEES, BIPS))
RELEASE_SUFFIX = "-retained-fee-conformance"


def event_rows(path):
    """Read one bounded, owner-verified canonical stream."""
    if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_DOCUMENT_BYTES:
        raise EvidenceUnavailable("canonical event stream unavailable")
    with path.open("rb") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def release_conforms(generation, source, coverage, events):
    """Check present native targets against their exact independent fee rows.

    The full verifier remains the release authority. This extra check refuses
    a valid release that has omitted or retained unsupported fee targets.
    """
    if source["adapter"] != generation or coverage["versions"]["adapter"] != {
            "name": generation, "version": ADAPTER_VERSION}:
        return False
    unsupported = coverage["coverage"]["unsupported_events"]
    for key in unsupported:
        if any(signature in key for signature in (FEES, BIPS)):
            return False
        if key.startswith("decode:") and key.rsplit(":", 1)[-1] in TARGET_TOPICS:
            return False
    by_selector = {}
    for row in events:
        by_selector.setdefault(row["provenance"]["source_selector"], []).append(row)
    for record in source["mapping_records"]:
        signature = record["signature"]
        if signature not in (FEES, BIPS):
            continue
        if signature == BIPS and generation != "wildcat-v2":
            return False
        action = "fees-collected" if signature == FEES else "protocol-fee-bips-updated"
        rows = by_selector.get(record["source_selector"], [])
        if record["disposition"] != "primary" or record["emitter_role"] != "market" or len(rows) != 1:
            return False
        row = rows[0]
        pool = record["native_record"]["address"]
        if (row["action"] != generation + "." + action
                or row["provenance"]["mapping_rule"] != generation + "." + action + ".v1"
                or row["provenance"]["adapter_version"] != ADAPTER_VERSION
                or row["parties"] != [{"role": "pool", "address": pool}]
                or row["native_record"] != record["native_record"] or record["join"] is not None):
            return False
        if signature == FEES:
            if (row["event_family"] != "fee-collection"
                    or row["amounts"] != [{"kind": "assets", "base_units": record["decoded"]["assets"],
                                          "asset": record["context"]["asset"]}]):
                return False
        elif row["event_family"] != "pool-state" or row["amounts"]:
            return False
    return True


def retained_conformance(generations=GENERATIONS, environ=None, witness=None):
    """Return a qualified boolean and privacy-bounded observations.

    Both custody roots must pass before scratch creation. The caller receives
    no retained count, signature inventory or path. Scratch is removed on
    positive, negative, refusal and Python interruption paths; custody stays unchanged.
    """
    import os
    environ = os.environ if environ is None else environ
    if tuple(spec.generation for spec in generations) != VENUES:
        raise EvidenceUnavailable("both ordered Wildcat generations are required")
    roots = [(spec, spec.custody(environ)) for spec in generations]
    scratch = private_scratch()
    inputs, passed = [], []
    v2_collection = False
    value = True
    try:
        if witness is not None:
            witness(scratch)
        for spec, root in roots:
            raw = spec.rebuild(root, scratch / (spec.generation + "-raw"))
            canonical = scratch / (spec.generation + "-canonical")
            build_wildcat_canonical(raw, canonical, spec.generation + RELEASE_SUFFIX, ADAPTER_VERSION)
            try:
                verifier.verify(canonical / "coverage.json")
            except TabulariumError:
                value = False
                continue
            source = document(canonical / "source.json")
            coverage = document(canonical / "coverage.json")
            rows = event_rows(canonical / "events.jsonl")
            conformant = release_conforms(spec.generation, source, coverage, rows)
            if spec.generation == "wildcat-v2":
                v2_collection = any(record["signature"] == FEES and record["disposition"] == "primary"
                                    for record in source["mapping_records"])
            inputs.append({"generation": spec.generation,
                           "raw_release_id": source["raw_release"]["release_id"],
                           **{field: sha256_file(canonical / name) for field, name in DIGEST_FILES}})
            if conformant:
                passed.append(spec.generation)
            value = value and conformant
        if value and not v2_collection:
            raise EvidenceUnavailable("wildcat-v2 maps no fee collection")
    finally:
        shutil.rmtree(scratch)
    return value, {"inputs": inputs, "passed_generations": passed}


def retained_resolver(generations=GENERATIONS, witness=None):
    """Bind the retained operation for the immutable proof dispatcher."""
    def resolve():
        return retained_conformance(generations, witness=witness)
    return resolve
