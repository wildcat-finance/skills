"""Constructed routing specimens with positives, overlap and unmatched groups."""

from copy import deepcopy
import json
from pathlib import Path
import shutil
import tempfile

from wildcat_sanctions_fixtures import raws
from test_wildcat_v3_release import constructed_release
from wildcat_v3_public_fixtures import inventory, observation
from tabularium_lib.core import canonical_json
from tabularium_lib.wildcat_release import build_wildcat_canonical
from tabularium_lib import verifier

VENUES = ("wildcat-v1", "wildcat-v2")
EXAMPLES = Path(__file__).resolve().parents[1] / "examples"


def specimen_raws(venue):
    """Give each labelled control its own transaction and global log indices."""
    if venue not in VENUES:
        raise ValueError("unknown constructed generation")
    baseline = raws(venue)
    groups = [baseline, raws(venue, overlap=True)]
    pairs = [(0, 1), (2, 4)] if venue == "wildcat-v2" else [(0, 1)]
    for primary, companion in pairs:
        groups.append([row for i, row in enumerate(deepcopy(baseline)) if i != primary])
        for position in (primary, companion):
            group = deepcopy(baseline)
            group.append(deepcopy(group[position]))
            groups.append(group)
    result = []
    for transaction, group in enumerate(groups):
        for row in deepcopy(group):
            row["transactionHash"] = "0x" + format(transaction + 1, "064x")
            row["transactionIndex"] = hex(transaction)
            row["logIndex"] = hex(len(result))
            result.append(row)
    return result


def build_specimen(directory, venue):
    """Build a fresh schema-3 release with explicit adapter 1.3.0."""
    def replace(document, journal, plan):
        response = json.loads(journal["records"][0]["response"])
        response["result"] = specimen_raws(venue)
        journal["records"][0]["response"] = canonical_json(response).decode()
        plan["release"]["name"] = venue + "-constructed-sanctions"
    with tempfile.TemporaryDirectory(prefix="tabularium-sanctions-input-") as temporary:
        raw = constructed_release(Path(temporary).resolve(), venue, replace)
        release = Path(directory) / "release"
        build_wildcat_canonical(raw, release, venue + "-constructed-sanctions-v0", adapter_version="1.3.0")
    return {"release": observation(release)}


def rebuild_example(venue, examples=EXAMPLES):
    """Compare every generated byte, then verify the moved read-only root."""
    published = Path(examples) / (venue + "-sanctions-v0")
    expected = json.loads((published / "expected.json").read_bytes())
    with tempfile.TemporaryDirectory(prefix="tabularium-sanctions-rebuild-") as temporary:
        original = Path(temporary).resolve() / "original"
        original.mkdir()
        actual = build_specimen(original, venue)
        if actual != expected or inventory(original / "release") != inventory(published / "release"):
            raise ValueError("constructed sanctions inventory differs")
        for relative in actual["release"]["files"]:
            if (original / "release" / relative).read_bytes() != (published / "release" / relative).read_bytes():
                raise ValueError("constructed sanctions release bytes differ")
        moved = original.parent / "moved"
        shutil.move(original / "release", moved)
        shutil.rmtree(original)
        for path in moved.rglob("*"):
            if path.is_file():
                path.chmod(0o444)
        verifier.verify(moved / "coverage.json")
    return 0
